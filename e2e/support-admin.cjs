/** Emulator-only browser coverage. Use the isolated UI workspace from docs/web-preview.md. */
const { chromium } = require(process.env.MUSE_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { resolve } = require('node:path');
const { createRequire } = require('node:module');
const root = resolve(__dirname, '..');
const appUrl = process.env.MUSE_WEB_APP_URL || 'http://localhost:8081';
if (process.env.MUSE_WEB_QA !== 'demo-muse' || !['localhost', '127.0.0.1'].includes(new URL(appUrl).hostname)) throw new Error('Requires isolated demo-muse emulators and a loopback browser URL.');
process.env.GCLOUD_PROJECT = 'demo-muse';
process.env.FIREBASE_AUTH_EMULATOR_HOST = '127.0.0.1:9099';
process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8080';
const backendRequire = createRequire(resolve(root, 'firebase/functions/package.json'));
const { initializeApp } = backendRequire('firebase-admin/app');
const { getAuth } = backendRequire('firebase-admin/auth');
const { getFirestore } = backendRequire('firebase-admin/firestore');
initializeApp({ projectId: 'demo-muse' });
const db = getFirestore();

async function run() {
  execFileSync(process.execPath, [resolve(root, 'firebase/functions/scripts/seed.js')], { env: process.env, stdio: 'pipe' });
  await getAuth().setCustomUserClaims('muse_dev', { moderator: true, supportAccess: true });
  await db.doc('supportOperators/muse_dev').set({ enabled: true });
  const beforeAccount = await getAuth().getUser('muse_alexa');
  const beforeMatch = (await db.doc('matches/muse_alexa_muse_jules').get()).data();
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const failures = [];
  context.on('page', p => p.on('pageerror', error => failures.push(error.message)));
  const admin = await context.newPage();
  admin.setDefaultTimeout(60_000);
  try {
    await admin.goto(appUrl);
    await admin.getByTestId('welcome-sign-in').click();
    await admin.getByTestId('signin-email').fill('muse+dev@example.com');
    await admin.getByTestId('signin-password').fill('Password123!');
    await admin.getByTestId('signin-submit').click();
    await admin.getByTestId('tab-profile').click();
    await admin.getByTestId('profile-settings').click();
    await admin.getByTestId('settings-member-admin').click();
    await admin.getByTestId('admin-tab-woman').click();
    await admin.getByTestId('admin-member-muse_alexa').waitFor();
    assert.equal(await admin.getByTestId('admin-member-muse_jules').count(), 0);
    await admin.getByTestId('admin-member-lookup').fill('muse+alexa@example.com');
    await admin.getByRole('button', { name: 'Find member', exact: true }).click();
    await admin.getByTestId('support-start').waitFor();
    assert(await admin.getByTestId('support-start').isDisabled());
    await admin.getByTestId('support-reason').fill('QA ticket 104: inspect matches without marking them read');
    const popup = context.waitForEvent('page');
    await admin.getByTestId('support-start').click();
    const support = await popup;
    support.setDefaultTimeout(60_000);
    await support.getByTestId('support-banner').waitFor();
    assert.match(await support.getByTestId('support-banner').innerText(), /Viewing Alexa.*Read-only/);
    await support.getByTestId('tab-matches').click();
    await support.getByTestId('match-row-muse_alexa_muse_jules').click();
    await support.getByTestId("chat-message-latest").getByText("Can't wait to meet!", { exact: true }).waitFor();
    const afterMatch = (await db.doc('matches/muse_alexa_muse_jules').get()).data();
    assert.deepEqual(afterMatch.lastReadAt, beforeMatch.lastReadAt);
    assert.deepEqual(afterMatch.unread, beforeMatch.unread);
    assert.equal((await getAuth().getUser('muse_alexa')).metadata.lastSignInTime, beforeAccount.metadata.lastSignInTime);
    assert.equal(await support.evaluate(() => Object.keys(localStorage).some(k => k.includes('paire-support'))), false);
    assert.equal(await support.evaluate(() => location.search), '?support=1');
    await admin.reload();
    await admin.getByTestId('tab-profile').click();
    // The original tab's persistent login must still be the owner, including moderator tools.
    await admin.getByTestId('profile-settings').click();
    await admin.getByTestId('settings-member-admin').click();
    await admin.getByTestId('admin-member-muse_alexa').click();
    await admin.getByRole('button', { name: 'End session', exact: true }).click();
    await support.getByRole('heading', { name: 'Support session ended' }).waitFor();
    assert.equal(await support.getByTestId('tab-matches').count(), 0);
    await admin.getByTestId('support-reason').fill('QA ticket 105: confirm refresh has no persistent support token');
    const popup2 = context.waitForEvent('page');
    await admin.getByTestId('support-start').click();
    const refreshed = await popup2;
    refreshed.setDefaultTimeout(60_000);
    await refreshed.getByTestId('support-banner').waitFor();
    await refreshed.reload();
    await refreshed.getByRole('heading', { name: 'Support session ended' }).waitFor();
    assert.equal(await refreshed.getByTestId('tab-profile').count(), 0);
    await admin.getByRole('button', { name: 'End session', exact: true }).click();
    await admin.getByRole('button', { name: 'Go back', exact: true }).click();
    await admin.getByTestId('admin-member-lookup').fill('muse+onboard@example.com');
    await admin.getByRole('button', { name: 'Find member', exact: true }).click();
    await admin.getByTestId('support-reason').fill('QA ticket 106: investigate onboarding before any profile exists');
    const popup3 = context.waitForEvent('page');
    await admin.getByTestId('support-start').click();
    const onboarding = await popup3;
    onboarding.setDefaultTimeout(60_000);
    await onboarding.getByTestId('support-banner').waitFor();
    await onboarding.getByTestId('basics-name').waitFor();
    assert.equal((await db.doc('users/muse_onboard').get()).exists, false);
    await onboarding.getByRole('button', { name: 'Exit support session', exact: true }).click();
    await onboarding.getByRole('heading', { name: 'Support session ended' }).waitFor();
    assert.deepEqual(failures, []);
    console.log('PASS admin lookup, gender tabs, support identity/view, chat read without receipts, preserved admin login, revocation, memory-only refresh, incomplete onboarding and Exit');
  } finally {
    const sessions = await db.collection('supportSessions').where('actorUid', '==', 'muse_dev').get();
    for (const session of sessions.docs) await session.ref.update({ endedAt: Date.now() });
    await browser.close();
  }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
